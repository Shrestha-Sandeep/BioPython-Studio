// Shared microscopy-to-report visual; images are credited Witz/HPA notebook outputs.
// They are NOT evidence that the beginner tutorial segmented or measured a field.
"use strict";
(() => {
  const currentChapter=Object.freeze({
    P01:["Today's piece","Store a specimen ID, an observed count, and a scale"],
    P02:["Today's piece","Validate the recorded specimen label before analysis"],
    P03:["Today's piece","Visit every field and document exclusions"],
    P04:["Today's piece","Attach verified metadata to each specimen ID"],
    P05:["Today's piece","Reuse and test calibrated measurement functions"],
    P06:["Today's piece","Save and check a reproducible specimen report"]
  });
  const stages=Object.freeze([
    {name:"Microscope image",tag:"Published figure",image:"./assets/witz/fluorescence-single.png",alt:"Published Witz/Human Protein Atlas fluorescence teaching figure. Not measured by this chapter."},
    {name:"Identify structures",tag:"Published example",image:"./assets/witz/otsu-nuclei-mask.png",alt:"Published Witz thresholding output figure, separate teaching illustration, not generated by beginner code."},
    {name:"Record measurements",tag:"Training inputs",lines:["Manually counted: {CELLS} cells","Measured distance: 40 px"]},
    {name:"Make a report",tag:"Hypothetical result",lines:["Specimen S01","Length 8.0 µm"]}
  ]);
  const make=(tag,className,text)=>{
    const node=document.createElement(tag);
    if(className)node.className=className;
    if(text!==undefined)node.textContent=text;
    return node;
  };
  function render(container,chapter,parameter=25){
    container.replaceChildren();
    const context=currentChapter[chapter];
    if(!context)return false;
    const figure=make("div","bps-example-workflow");
    figure.setAttribute("role","group");
    figure.setAttribute("aria-label","Scientific workflow preview, not a result produced by the Python lesson");
    const head=make("div","bps-example-workflow-head");
    head.append(make("strong","","One scientific workflow"),make("small","","Future image analysis · current lesson uses supplied numbers"));
    figure.append(head);
    const grid=make("div","bps-example-workflow-grid");
    stages.forEach((item,i)=>{
      const tile=make("div","bps-example-workflow-tile");
      tile.setAttribute("data-bps-workflow-stage",String(i+1));
      const title=make("div","bps-example-workflow-title");
      title.append(make("span","",String(i+1).padStart(2,"0")),make("strong","",item.name));
      tile.append(title);
      if(item.image){
        const img=make("img","bps-example-workflow-image");
        img.src=item.image;img.alt=item.alt;img.loading="lazy";
        tile.append(img);
      }else{
        const output=make("div","bps-example-workflow-plain");
        for(const value of item.lines)output.append(make("span","",value.replace("{CELLS}",String(parameter))));
        tile.append(output);
      }
      tile.append(make("small","bps-example-workflow-tag",item.tag));
      grid.append(tile);
    });
    figure.append(grid);
    const focus=make("div","bps-example-workflow-focus");
    focus.append(make("span","",chapter+" · "+context[0]),make("strong","",context[1]));
    figure.append(focus);
    const disclaimer=make("p","bps-example-workflow-caveat");
    disclaimer.append(document.createTextNode("Published teaching figures are illustrative; numerical values are invented and not extracted from these images. "));
    const link=make("a","","Image credits");
    link.href="./assets/witz/CREDITS.md";link.target="_blank";link.rel="noopener noreferrer";
    disclaimer.append(link);
    figure.append(disclaimer);
    container.append(figure);
    return true;
  }
  window.BioPythonMicroscopyWorkflow=Object.freeze({render});
})();
